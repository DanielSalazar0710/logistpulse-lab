-- V1: esquema que Hibernate generaba con ddl-auto=update (punto de partida del laboratorio).
-- En una base que ya existía, Flyway la marca como "baseline" (spring.flyway.baseline-on-migrate) y no la ejecuta.
CREATE TABLE warehouse (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(255) NOT NULL UNIQUE,
    originx INTEGER NOT NULL,
    originy INTEGER NOT NULL
);

CREATE TABLE robot (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(20) NOT NULL UNIQUE,
    warehouse_id BIGINT NOT NULL REFERENCES warehouse (id),
    x            INTEGER NOT NULL,
    y            INTEGER NOT NULL,
    battery      INTEGER NOT NULL,
    status       VARCHAR(10) NOT NULL,
    version      BIGINT NOT NULL,
    CONSTRAINT robot_status_check CHECK (status IN ('IDLE', 'BUSY'))
);

CREATE TABLE orders (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(20) NOT NULL UNIQUE,
    customer_name VARCHAR(80) NOT NULL,
    destx         INTEGER NOT NULL,
    desty         INTEGER NOT NULL,
    status        VARCHAR(20) NOT NULL,
    warehouse_id  BIGINT NOT NULL REFERENCES warehouse (id),
    robot_id      BIGINT REFERENCES robot (id),
    eta_minutes   INTEGER,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version       BIGINT NOT NULL,
    CONSTRAINT orders_status_check
        CHECK (status IN ('CREATED', 'DISPATCHED', 'IN_TRANSIT', 'DELIVERED', 'CANCELLED'))
);

CREATE INDEX idx_orders_status ON orders (status);
